function getFeedbackHtml(message) {
  const paragraphs = message.includes("\n") ? message.split("\n") : message.match(/[^。！？]+[。！？]?/g);
  const cleanParagraphs = paragraphs.map((paragraph) => paragraph.trim()).filter(Boolean);

  return cleanParagraphs.map((paragraph, index) => {
    const prefix = index === 0 ? "“" : "";
    const suffix = index === cleanParagraphs.length - 1 ? "”" : "";

    return `<p>${prefix}${paragraph}${suffix}</p>`;
  }).join("");
}

