function handleInterludeCardClick(clueId) {
  if (hasPlayedInterludeFinale || isInterludeAnimating) {
    return;
  }

  if (!selectedInterludeClueId) {
    selectedInterludeClueId = clueId;
    setInterludeSelectedCard(clueId);
    interludeHint.textContent = "再选择一张线索卡片。";
    return;
  }

  if (selectedInterludeClueId === clueId) {
    selectedInterludeClueId = null;
    setInterludeSelectedCard("");
    interludeHint.textContent = "已取消选择。";
    return;
  }

  connectInterludeClues(selectedInterludeClueId, clueId);
  selectedInterludeClueId = null;
  setInterludeSelectedCard("");
}

function connectInterludeClues(firstClueId, secondClueId) {
  const pairKey = getPairKey(firstClueId, secondClueId);
  const line = drawInterludeLine(firstClueId, secondClueId);

  if (completedInterludePairs.has(pairKey)) {
    interludeHint.textContent = "这组线索已经记录过了。";
    line.remove();
    return;
  }

  if (!checkCurrentPairCorrect(pairKey)) {
    line.classList.add("fail");
    shakeInterludeCards(firstClueId, secondClueId);
    interludeHint.textContent = "关联不足。";

    window.setTimeout(() => {
      line.remove();
      clearInterludeCardShake(firstClueId, secondClueId);
    }, 700);
    return;
  }

  const currentQuestion = activeDeductionQuestions[currentDeductionQuestionIndex];
  isInterludeAnimating = true;
  completedInterludePairs.add(pairKey);
  completedInterludeQuestions.add(currentQuestion.id);
  line.classList.add("success");
  markInterludeCardsLinked(firstClueId, secondClueId);
  interludeHint.textContent = "关联成立。";
  playCorrectConnectionAnimation(line, currentQuestion);
}

function drawInterludeLine(firstClueId, secondClueId) {
  const firstCard = document.querySelector(`[data-interlude-clue="${firstClueId}"]`);
  const secondCard = document.querySelector(`[data-interlude-clue="${secondClueId}"]`);
  const areaRect = interludeCardArea.getBoundingClientRect();
  const firstRect = firstCard.getBoundingClientRect();
  const secondRect = secondCard.getBoundingClientRect();
  const line = document.createElementNS("http://www.w3.org/2000/svg", "line");

  line.setAttribute("x1", firstRect.left + firstRect.width / 2 - areaRect.left);
  line.setAttribute("y1", firstRect.top + firstRect.height / 2 - areaRect.top);
  line.setAttribute("x2", secondRect.left + secondRect.width / 2 - areaRect.left);
  line.setAttribute("y2", secondRect.top + secondRect.height / 2 - areaRect.top);
  line.classList.add("interlude-line");
  line.dataset.pairKey = getPairKey(firstClueId, secondClueId);
  interludeLineLayer.appendChild(line);

  return line;
}

