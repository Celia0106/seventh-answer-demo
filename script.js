function getStorySketchType(text) {
  if (text.includes("大厅的钟声敲过零点")) {
    return "clock";
  }

  if (text.includes("红光忽然灭了") || text.includes("盥洗室的灯灭了")) {
    return "lamp";
  }

  if (text.includes("“旧钥匙。”") || text.includes("手里攥着旧钥匙")) {
    return "key";
  }

  if (text.includes("一支沾着灰的录音笔。")) {
    return "recorder";
  }

  if (text.includes("录音里传来一声极轻的金属碰撞声")) {
    return "tape";
  }

  if (text.includes("裂痕从中央斜斜划过") || text.includes("裂开的镜面里") || text.includes("裂开的镜子")) {
    return "mirror";
  }

  if (text.includes("银刀相互碰撞") || text.includes("银刀被装进证物袋")) {
    return "knife";
  }

  if (text.includes("无人遗忘，便无人脱身") || text.includes("案件调查结束") || text.includes("主谋身份存疑")) {
    return "file";
  }

  if (text.includes("庄园被重新封锁")) {
    return "lock";
  }

  if (text.includes("雪地里留下的脚印")) {
    return "footprints";
  }

  if (text.trim() === "天光大亮。") {
    return "mlrd";
  }

  if (text.includes("而如今，天光大亮")) {
    return "clearing";
  }

  if (text.includes("天光大亮") || text.includes("雪停之后") || text.includes("新的雪覆盖")) {
    return "snow";
  }

  if (text.includes("长桌上多出的座位") || text.includes("座位被撤走") || text.includes("座位被一张张撤下")) {
    return "seat";
  }

  return "";
}

