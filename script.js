function getPrologueHtml(scene, index, titleTag, subtitleHtml, statusText, isLocked) {
  const pages = scene.storyBlocks.map((block, pageIndex) => {
    const isFirstPage = pageIndex === 0;
    const isLastPage = pageIndex === scene.storyBlocks.length - 1;
    const headingHtml = isFirstPage ? `
      <${titleTag}>${scene.title}</${titleTag}>
      ${subtitleHtml}
    ` : "";
    const paragraphs = block.map((text, lineIndex) => {
      const unsettlingClass = text.includes("六个人同时看见") || text.includes("第七个座位") ? " unsettling" : "";
      const delay = `${lineIndex * 0.16}s`;

        return `<p class="scene-text story-line${unsettlingClass}" style="transition-delay: ${delay}">${text}</p>${getStorySketchHtml(text)}`;
    }).join("");
    const actionHtml = isLastPage ? `
      <div class="scene-actions">
        <button class="primary-button scene-button" type="button" data-scene-index="${index}" ${isLocked ? "disabled" : ""}>
          ${scene.buttonText}
        </button>
      </div>
      <p class="scene-status">${statusText}</p>
    ` : `<div class="scroll-cue" aria-hidden="true"></div>`;

    return `
      <div class="story-page">
        <div class="story-page-inner">
          ${headingHtml}
          ${paragraphs}
          ${actionHtml}
        </div>
      </div>
    `;
  }).join("");

  return `<div class="scene-content prologue-content">${pages}</div>`;
}

function getPagedChapterHtml(scene, index, titleTag, subtitleHtml, statusText, isLocked) {
  const pages = scene.storyBlocks.map((block, pageIndex) => {
    const isFirstPage = pageIndex === 0;
    const isLastPage = pageIndex === scene.storyBlocks.length - 1;
    const headingHtml = isFirstPage ? `
      <${titleTag}>${scene.title}</${titleTag}>
      ${subtitleHtml}
    ` : "";
    const paragraphs = block.map((text, lineIndex) => {
      const delay = `${lineIndex * 0.14}s`;

      return `<p class="scene-text story-line" style="transition-delay: ${delay}">${text}</p>${getStorySketchHtml(text)}`;
    }).join("");
    const actionHtml = isLastPage ? `
      <div class="scene-actions">
        <button class="primary-button scene-button" type="button" data-scene-index="${index}" ${isLocked ? "disabled" : ""}>
          ${scene.buttonText}
        </button>
      </div>
      <p class="scene-status">${statusText}</p>
    ` : `<div class="scroll-cue" aria-hidden="true"></div>`;

    return `
      <div class="story-page">
        <div class="story-page-inner">
          ${headingHtml}
          ${paragraphs}
          ${actionHtml}
        </div>
      </div>
    `;
  }).join("");

  return `<div class="scene-content chapter-content">${pages}</div>`;
}

function getLetterRevealHtml(text, lineIndex) {
  return Array.from(text).map((character, characterIndex) => {
    const delay = (0.36 + lineIndex * 0.82 + characterIndex * 0.055).toFixed(2);

    return `<span class="letter-char" style="--letter-delay: ${delay}s">${escapeHtmlText(character)}</span>`;
  }).join("");
}

function escapeHtmlText(text) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

