      <div class="final-question-topline">
        <span>QUESTION ${String(questionNumber).padStart(2, "0")} / ${String(finalQuestions.length).padStart(2, "0")}</span>
        <span>${question.type === "choice" ? "SELECT" : "TYPE"}</span>
      </div>
