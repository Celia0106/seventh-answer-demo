function renderScenes() {
  sceneContainer.innerHTML = "";

  scenes.forEach((scene, index) => {
    const section = document.createElement("section");
    section.className = `scene ${scene.chapter || ""}`;
    section.id = `scene-${index}`;

    if (index > unlockedSceneIndex) {
      section.classList.add("locked");
    }

    const titleTag = index === 0 ? "h1" : "h2";
    const textHtml = scene.storyBlocks || scene.chapter === "prologue" ? "" : getSceneTextHtml(scene);
    const isLocked = index > unlockedSceneIndex;
    const statusText = getSceneStatusText(index);
    const subtitleHtml = scene.subtitle ? `<p class="scene-subtitle">${scene.subtitle}</p>` : "";

    if (scene.chapter === "prologue") {
      section.innerHTML = getPrologueHtml(scene, index, titleTag, subtitleHtml, statusText, isLocked);
    } else if (scene.chapter === "final") {
      section.innerHTML = getFinalChapterHtml(scene, index, titleTag, subtitleHtml, statusText, isLocked);
    } else if (scene.storyBlocks) {
      section.innerHTML = getPagedChapterHtml(scene, index, titleTag, subtitleHtml, statusText, isLocked);
    } else {
      const actionsHtml = scene.isPlaceholder ? "" : `
          <div class="scene-actions">
            <button class="primary-button scene-button" type="button" data-scene-index="${index}" ${isLocked ? "disabled" : ""}>
              ${scene.buttonText}
            </button>
            ${index > 0 ? `<button class="ghost-button back-button" type="button" data-target-index="${index - 1}">回到上一幕</button>` : ""}
          </div>
      `;

      section.innerHTML = `
        <div class="scene-content">
          <${titleTag}>${scene.title}</${titleTag}>
          ${subtitleHtml}
          ${textHtml}
          ${actionsHtml}
          <p class="scene-status">${statusText}</p>
        </div>
      `;
    }

    sceneContainer.appendChild(section);
  });

  bindSceneButtons();
  bindFinalDoor();
  bindFinalLetter();
  observeStoryText();
  observeStorySketches();
  observeChapterOneShock();
  observeChapterThreeBlackout();
}

