function toggleClueMark(clue) {
  if (completedChapters.has(clue.chapter)) {
    unlockMessage.textContent = "这条关键线索已经记录过了。";
    return;
  }

  const wasMarked = markedClues.has(clue.id);
  const recordedKeySet = getRecordedKeySet(clue.chapter);

  if (markedClues.has(clue.id)) {
    markedClues.delete(clue.id);
    if (clue.isKey) {
      recordedKeySet.delete(clue.id);
    }
  } else {
    markedClues.add(clue.id);
    if (clue.isKey) {
      recordedKeySet.add(clue.id);
    }
  }

  const scene = scenes[currentSceneIndex];
  renderClues(scene);
  showClueDetail(clue);
  checkSceneUnlock(clue, wasMarked);
}

function checkSceneUnlock(clue, wasMarked) {
  const scene = scenes[currentSceneIndex];
  const keyClues = scene.clues.filter((item) => item.isKey);
  const recordedKeySet = getRecordedKeySet(scene.chapter);
  const foundKeyCount = keyClues.filter((item) => recordedKeySet.has(item.id)).length;
  const requiredKeyCount = getRequiredKeyCount(scene);
  const foundEnoughKeyClues = foundKeyCount >= requiredKeyCount;

  if (wasMarked) {
    unlockMessage.textContent = "线索标记已取消。";
    return;
  }

  if (!clue.isKey) {
    unlockMessage.textContent = "这条线索值得注意，但还不足以解开当前问题。";
    return;
  }

  if (!foundEnoughKeyClues) {
    unlockMessage.textContent = "关键线索已记录。";
    return;
  }

  if (scene.chapter === "prologue" && !isPrologueCompleted && foundEnoughKeyClues) {
    showPrologueSubmitPrompt();
    return;
  }

  if (scene.chapter !== "prologue" && !completedChapters.has(scene.chapter) && foundEnoughKeyClues) {
    showChapterSubmitPrompt(scene);
    return;
  }

  unlockMessage.textContent = "这一幕的关键线索已经找齐。";
}

