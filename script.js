function getEndingStoryPages(body) {
  const lines = body.split(/\n\s*\n/).map((line) => line.trim()).filter(Boolean);
  const pageSize = 6;
  const responsibilityQuestions = [
    "谁关上了门？",
    "谁拿走了钥匙？",
    "谁改写了时间？",
    "谁在教人说谎？",
    "谁把谎言写成真相？",
    "谁让法律闭上眼睛？"
  ];
  const responsibilityStart = lines.findIndex((line) => line === responsibilityQuestions[0]);

  if (responsibilityStart > -1) {
    const responsibilityEnd = lines.findIndex((line, index) => index > responsibilityStart && line === "每个人都在各司其职，");
    const questionIndexes = responsibilityQuestions
      .map((question) => lines.findIndex((line) => line === question))
      .filter((index) => index > -1);
    const pages = [
      ...chunkEndingLines(lines.slice(0, responsibilityStart), pageSize)
    ];

    questionIndexes.forEach((questionIndex, index) => {
      const nextQuestionIndex = questionIndexes[index + 1];
      const endIndex = nextQuestionIndex || (responsibilityEnd > -1 ? responsibilityEnd : lines.length);
      pages.push(lines.slice(questionIndex, endIndex));
    });

    if (responsibilityEnd > -1) {
      pages.push(...chunkEndingLines(lines.slice(responsibilityEnd), pageSize));
    }

    return pages.filter((page) => page.length);
  }

  return chunkEndingLines(lines, pageSize);
}

function chunkEndingLines(lines, pageSize) {
  const pages = [];

  for (let index = 0; index < lines.length; index += pageSize) {
    pages.push(lines.slice(index, index + pageSize));
  }

  return pages;
}

