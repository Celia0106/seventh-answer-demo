function getFinalQuestionBody(question, storedAnswer) {
  if (question.type === "choice") {
    const letters = ["A", "B", "C", "D", "E", "F"];
    const optionsHtml = question.options.map((option, index) => {
      const letter = letters[index];
      const isSelected = storedAnswer === letter;

      return `
        <button class="final-answer-card${isSelected ? " selected" : ""}" type="button" data-final-answer="${letter}">
          <span class="final-answer-letter">${letter}</span>
          <span>${escapeHtmlText(option)}</span>
        </button>
      `;
    }).join("");

    const compactClass = question.options.length > 4 ? " compact" : "";

    return `<div class="final-answer-grid${compactClass}">${optionsHtml}</div>`;
  }

  const rosterHtml = question.roster ? `
    <div class="final-roster" aria-label="人物名单">
      ${question.roster.map((item) => `<span>${escapeHtmlText(item)}</span>`).join("")}
    </div>
  ` : "";

  return `
    ${rosterHtml}
    <label class="final-text-answer">
      <span>${question.type === "suspect" ? "输入凶手" : "输入答案"}</span>
      <input type="text" data-final-input value="${escapeHtmlText(storedAnswer || "")}" autocomplete="off">
    </label>
  `;
}

