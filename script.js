function isFinalAnswerCorrect(question) {
  const answer = finalQuizState.answers[question.id] || "";

  if (question.type === "choice") {
    return answer === question.correctAnswer;
  }

  return question.acceptedAnswers.some((acceptedAnswer) => {
    return normalizeFinalAnswer(answer) === normalizeFinalAnswer(acceptedAnswer);
  });
}

function normalizeFinalAnswer(answer) {
  return String(answer)
    .replace(/\s+/g, "")
    .replace(/，/g, ",")
    .replace(/、/g, ",")
    .toLowerCase();
}

